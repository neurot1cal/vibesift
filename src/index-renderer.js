// Landing-page sessions list regenerator. Scans docs/sessions/*, parses each
// session's embedded state, and rewrites the block between the
// VIBESIFT:SESSIONS:START / VIBESIFT:SESSIONS:END markers in docs/index.html.
//
// Delimiter parsing uses indexOf, not regex. The state-block parser in
// src/state.js made the same call after CodeQL flagged backtracking risks
// on lazy quantifiers; this file follows the same convention so the same
// rule (no regex breakouts) carries through the new code path.
//
// Everything outside the markers is preserved byte-for-byte. The hero,
// verb cards, footer, and inline theme-toggle script are hand-curated;
// this regenerator deliberately doesn't touch them.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { parseState } from './state.js';
import { escapeHtml } from './template.js';

export const START_MARKER = '<!-- VIBESIFT:SESSIONS:START -->';
export const END_MARKER = '<!-- VIBESIFT:SESSIONS:END -->';
export const REGEN_NOTICE =
  "<!-- Sessions list regenerated by 'vibesift index'. " +
  'Hand-edits between START/END markers will be overwritten. -->';

// Match the existing row markup exactly. Status pip is `is-active` whenever
// phase != ship OR ship.shippedAt is null; the plain (green) pip only fires
// once a ship decision has been recorded.
function statusClassAndLabel(state) {
  const shipped = state.phase === 'ship' && !!state.ship && !!state.ship.shippedAt;
  if (shipped) {
    return { cls: 'sess-status', label: 'shipped' };
  }
  if (state.phase === 'ship') {
    return { cls: 'sess-status is-active', label: 'active · ship' };
  }
  return { cls: 'sess-status is-active', label: `active · ${state.phase}` };
}

function fmtDay(ts) {
  if (!ts) return '';
  return new Date(ts).toISOString().slice(0, 10);
}

export function renderSessionRow(state) {
  const { cls, label } = statusClassAndLabel(state);
  const date = fmtDay(state.updatedAt);
  const slug = encodeURIComponent(state.slug);
  // Match the existing markup pattern in docs/index.html. Title gets escaped
  // because it can contain &, <, >, " or '; slug is encodeURIComponent'd
  // because it ends up in an href attribute. Static class names (sess-row,
  // sess-date, sess-status, sess-title, sess-arrow) come from this file's
  // own constants — no user data flows into them.
  //
  // Caller (renderSessionsBlock) prepends 4 spaces of base indent before the
  // opening <a>. The 6-space prefix on each child span lines them up two
  // levels deeper, matching the indent style of the original hand-coded
  // sessions list in docs/index.html.
  return [
    `<a class="sess-row" href="sessions/${slug}/">`,
    `      <span class="sess-date">${escapeHtml(date)}</span>`,
    `      <span class="${cls}">${escapeHtml(label)}</span>`,
    `      <span class="sess-title"><span>${escapeHtml(state.title || state.slug)}</span><span class="sess-arrow">→</span></span>`,
    `    </a>`,
  ].join('\n');
}

// Discover sessions: read each docs/sessions/<slug>/index.html and parse the
// state block. Skip dirs that don't have a parseable session.
export function discoverSessions(repoRoot) {
  const sessionsDir = join(repoRoot, 'docs', 'sessions');
  if (!existsSync(sessionsDir)) return [];
  const out = [];
  const entries = readdirSync(sessionsDir, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const path = join(sessionsDir, entry.name, 'index.html');
    if (!existsSync(path)) continue;
    let state;
    try {
      state = parseState(readFileSync(path, 'utf8'));
    } catch {
      continue; // unparseable — skip silently, same convention as cmdList
    }
    out.push(state);
  }
  // Newest first.
  out.sort((a, b) => (b.updatedAt || 0) - (a.updatedAt || 0));
  return out;
}

// Build the inner HTML that lives between the markers. Includes a leading
// newline + trailing newline + indentation that reads cleanly inside the
// existing <section class="sessions"> block.
export function renderSessionsBlock(sessions) {
  if (!sessions.length) {
    return '\n    <p class="empty">No sessions yet. Run <code>vibesift init &lt;slug&gt; --title "..."</code> to create one.</p>\n  ';
  }
  // Each row is prefixed by 4 spaces so it sits two levels deep inside the
  // <section> tag, matching the indent style of the surrounding hero / verb
  // / footer blocks. Rows are joined with a newline + the same prefix.
  const rows = sessions.map(renderSessionRow).map(r => `    ${r}`).join('\n');
  return `\n${rows}\n  `;
}

// Migration path: the landing was hand-written before vibesift index existed.
// First time we run, find the existing <section class="sessions" ...> block
// and wrap its inner content in markers. Idempotent: running again does
// nothing destructive (later branch in updateBetweenMarkers takes over).
function injectMarkersAndNotice(html) {
  // Look for the sessions section. Use indexOf on a stable substring.
  const sectionTag = '<section class="sessions"';
  const sectionIdx = html.indexOf(sectionTag);
  if (sectionIdx < 0) {
    throw new Error("docs/index.html has no <section class=\"sessions\"> block — can't migrate");
  }
  // Inside that section, the heading is preserved; markers wrap whatever
  // comes AFTER the heading's closing </h3>. We pin to the LAST </h3> before
  // the section closes, so the markers wrap the row list specifically and
  // leave the section heading untouched.
  const sectionCloseIdx = html.indexOf('</section>', sectionIdx);
  if (sectionCloseIdx < 0) {
    throw new Error("docs/index.html has an unclosed sessions <section>");
  }
  // Find the last </h3> within this section.
  let cursor = sectionIdx;
  let lastH3Close = -1;
  while (true) {
    const next = html.indexOf('</h3>', cursor);
    if (next < 0 || next > sectionCloseIdx) break;
    lastH3Close = next;
    cursor = next + 5;
  }
  let injectAt;
  if (lastH3Close < 0) {
    // No heading inside — inject right after the opening tag's `>`.
    const openTagEnd = html.indexOf('>', sectionIdx);
    if (openTagEnd < 0 || openTagEnd > sectionCloseIdx) {
      throw new Error("docs/index.html sessions <section> open tag malformed");
    }
    injectAt = openTagEnd + 1;
  } else {
    injectAt = lastH3Close + 5; // length of </h3>
  }
  // The pre-marker text we capture preserves whitespace AFTER injectAt (so
  // the existing row indent stays consistent). Inner text is everything
  // between injectAt and sectionCloseIdx; we wrap it in markers verbatim.
  const innerStart = injectAt;
  const innerEnd = sectionCloseIdx;
  const inner = html.slice(innerStart, innerEnd);
  const head = html.slice(0, innerStart);
  const tail = html.slice(innerEnd);
  // Wrap inner content in markers. Preserve the inner content as-is during
  // migration; the next regen pass will replace it.
  let withMarkers =
    head +
    `\n    ${START_MARKER}` +
    inner.replace(/^\n?/, '\n    ').replace(/\s*$/, '') +
    `\n    ${END_MARKER}\n  ` +
    tail;
  // Add the regen notice once, near the top of the file. Place it right
  // after <!doctype html>. Idempotent — skip if already present.
  if (!withMarkers.includes(REGEN_NOTICE)) {
    const docIdx = withMarkers.toLowerCase().indexOf('<!doctype html>');
    if (docIdx >= 0) {
      const after = docIdx + '<!doctype html>'.length;
      withMarkers =
        withMarkers.slice(0, after) +
        '\n' + REGEN_NOTICE +
        withMarkers.slice(after);
    } else {
      withMarkers = REGEN_NOTICE + '\n' + withMarkers;
    }
  }
  return withMarkers;
}

// Replace the content between the START/END markers with a fresh sessions
// block. indexOf-based, no regex. Returns the rewritten HTML.
function updateBetweenMarkers(html, replacement) {
  const startIdx = html.indexOf(START_MARKER);
  if (startIdx < 0) throw new Error('START marker not found after migration');
  const afterStart = startIdx + START_MARKER.length;
  const endIdx = html.indexOf(END_MARKER, afterStart);
  if (endIdx < 0) throw new Error('END marker not found after START');
  return html.slice(0, afterStart) + replacement + html.slice(endIdx);
}

// Public entry point. Reads docs/index.html, regenerates the sessions block
// (migrating markers in on first run), and writes back. Returns metadata so
// the CLI caller can decide whether to commit.
//
// Reads via try/catch on readFileSync rather than `existsSync` + `readFileSync`
// to avoid the TOCTOU pattern CodeQL flags as `js/file-system-race`. The
// project's convention (see src/cli.js bootstrap) is to let the fs operation
// throw and translate ENOENT into a friendlier message, never gate writes on
// a separate existsSync check.
export function regenerateLandingIndex({ repoRoot }) {
  const indexPath = join(repoRoot, 'docs', 'index.html');
  let before;
  try {
    before = readFileSync(indexPath, 'utf8');
  } catch (e) {
    if (e.code === 'ENOENT') {
      throw new Error(`docs/index.html not found at ${indexPath} — run \`vibesift bootstrap\` first`);
    }
    throw e;
  }
  let working = before;
  if (working.indexOf(START_MARKER) < 0 || working.indexOf(END_MARKER) < 0) {
    working = injectMarkersAndNotice(working);
  }
  const sessions = discoverSessions(repoRoot);
  const block = renderSessionsBlock(sessions);
  const after = updateBetweenMarkers(working, block);
  if (after === before) {
    return { path: indexPath, before, after, changed: false, sessions };
  }
  writeFileSync(indexPath, after);
  return { path: indexPath, before, after, changed: true, sessions };
}
